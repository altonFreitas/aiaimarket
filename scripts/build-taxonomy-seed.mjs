#!/usr/bin/env node
/**
 * Generates supabase/taxonomy-seed.sql from the parsed specification.
 *
 *   npx tsx scripts/build-taxonomy-seed.mjs
 *
 * WHY GENERATED AND NOT HAND-WRITTEN. The specification carries 25
 * categories, 267 product types, 546 attributes and 2,568 assignments
 * between them. Typing that by hand would be four thousand lines nobody
 * could review and one typo would put Sleeve Length on a sofa.
 *
 * The INPUTS are both reviewable, which is the point:
 *   - supabase/seed-data/taxonomy.json -- what the specification says,
 *     parsed from the PDF exactly once.
 *   - src/lib/taxonomy/fieldTypes.ts   -- what kind of field each
 *     attribute is, with tests.
 *
 * IDEMPOTENT, because every SQL file in this project is pasted by hand and
 * may be pasted twice. Rows are keyed on slug and every insert carries an
 * ON CONFLICT, so a second run changes nothing -- and, deliberately, does
 * NOT overwrite an attribute the owner has since corrected in the
 * attribute builder. The seed sets a shop up; it does not police it
 * afterwards.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const { inferAttribute, slugify } =
  await import(path.join(ROOT, "src/lib/taxonomy/fieldTypes.ts"));

const tax = JSON.parse(
  fs.readFileSync(path.join(ROOT, "supabase/seed-data/taxonomy.json"), "utf8"));

const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

/* ---- collect the distinct things ------------------------------------- */
const cats = new Map();      // slug -> {name, order}
const subs = new Map();      // catSlug|subSlug -> {name, catSlug, order}
const types = [];            // {catSlug, subSlug, name, slug, order}
const attrs = new Map();     // slug -> AttributeSpec
const links = [];            // {typeKey, attrSlug, order}

for (const row of tax) {
  const catSlug = slugify(row.category);
  if (!cats.has(catSlug)) cats.set(catSlug, { name: row.category, order: cats.size });

  const subSlug = slugify(row.subcategory);
  const subKey = `${catSlug}|${subSlug}`;
  if (!subs.has(subKey)) {
    subs.set(subKey, { name: row.subcategory, catSlug, order: subs.size });
  }

  const typeSlug = slugify(row.product_type);
  const typeKey = `${subKey}|${typeSlug}`;
  types.push({ subKey, name: row.product_type, slug: typeSlug,
               order: types.length, key: typeKey });

  row.attributes.forEach((name, i) => {
    const spec = inferAttribute(name);
    if (!attrs.has(spec.slug)) attrs.set(spec.slug, spec);
    links.push({ typeKey, attrSlug: spec.slug, order: i });
  });
}

/* ---- emit ------------------------------------------------------------- */
const L = [];
L.push(`-- ===========================================================================
-- Loja AIAI -- the taxonomy itself
--
-- GENERATED by scripts/build-taxonomy-seed.mjs. Do not edit by hand: edit
-- supabase/seed-data/taxonomy.json (what the specification says) or
-- src/lib/taxonomy/fieldTypes.ts (what kind of field each attribute is),
-- then re-run the script and \`npm run sql\`.
--
-- Run AFTER supabase/taxonomy.sql. Safe to re-run: everything is keyed on
-- a slug and carries an ON CONFLICT, so a second paste changes nothing --
-- including nothing the owner has corrected in the attribute builder
-- since the first paste.
--
--   ${cats.size} categories
--   ${subs.size} subcategories
--   ${types.length} product types
--   ${attrs.size} attributes
--   ${links.length} attribute assignments
-- ===========================================================================

-- Categories and subcategories are rows in \`categories\`, which carries a
-- NOT NULL seller_id defaulting to current_seller_id(). The taxonomy is
-- the platform's, so it is filed under the settings row's seller -- the
-- same id the marketplace's own catalogue uses.
do $seed$
declare
  v_seller uuid;
begin
  select seller_id into v_seller from settings limit 1;
  if v_seller is null then
    raise exception 'No settings row: run supabase/schema.sql first.';
  end if;
`);

/* Bulk VALUES rather than one statement per row.
   These files are pasted into the Supabase SQL editor by hand. Emitted a
   statement at a time, the 2,568 assignments alone came to 1.1 MB, which
   is not a thing anybody can paste. As VALUES lists joined on slug it is a
   fraction of that, and each block is still one re-runnable statement. */
const vals = (rows) => rows.join(",\n    ");

/* categories */
L.push("  -- ---- categories ----");
L.push(`  insert into categories (seller_id, name, slug, parent_id, sort_order)
  select v_seller, v.name, v.slug, null, v.ord
    from (values
    ${vals([...cats].map(([slug, c]) => `(${q(c.name)}, ${q(slug)}, ${c.order})`))}
    ) as v(name, slug, ord)
  on conflict (seller_id, slug) do nothing;`);

/* subcategories */
L.push("\n  -- ---- subcategories (categories with a parent) ----");
L.push(`  -- The specification gives every category exactly one subcategory, and
  -- several share a name ("Clothing" under both Men's and Women's), so each
  -- slug is qualified by its parent to stay unique per seller.
  insert into categories (seller_id, name, slug, parent_id, sort_order)
  select v_seller, v.name, v.slug, c.id, v.ord
    from (values
    ${vals([...subs].map(([key, s2]) => {
      const [catSlug, subSlug] = key.split("|");
      return `(${q(s2.name)}, ${q(catSlug + "__" + subSlug)}, ${q(catSlug)}, ${s2.order})`;
    }))}
    ) as v(name, slug, parent_slug, ord)
    join categories c on c.seller_id = v_seller and c.slug = v.parent_slug
  on conflict (seller_id, slug) do nothing;`);

/* product types */
L.push("\n  -- ---- product types ----");
L.push(`  insert into product_types (category_id, name, slug, display_order)
  select c.id, v.name, v.slug, v.ord
    from (values
    ${vals(types.map((t) => {
      const [catSlug, subSlug] = t.subKey.split("|");
      return `(${q(t.name)}, ${q(t.slug)}, ${q(catSlug + "__" + subSlug)}, ${t.order})`;
    }))}
    ) as v(name, slug, cat_slug, ord)
    join categories c on c.seller_id = v_seller and c.slug = v.cat_slug
  on conflict (category_id, slug) do nothing;`);
L.push("end $seed$;\n");

/* attributes */
L.push("-- ---- attributes ----");
L.push(`insert into attributes
  (name, slug, field_type, unit, is_variant, filterable, searchable, sortable)
select v.name, v.slug, v.field_type, v.unit, v.is_variant, v.filterable, v.searchable, v.sortable
  from (values
  ${vals([...attrs.values()].map((a) =>
    `(${q(a.name)}, ${q(a.slug)}, ${q(a.fieldType)}, ${a.unit ? q(a.unit) : "null::text"}, ${a.variant}, ${a.filterable}, ${a.searchable}, ${a.sortable})`))}
  ) as v(name, slug, field_type, unit, is_variant, filterable, searchable, sortable)
on conflict (slug) do update set
    field_type = excluded.field_type,
    unit       = excluded.unit,
    is_variant = excluded.is_variant,
    filterable = excluded.filterable,
    searchable = excluded.searchable,
    sortable   = excluded.sortable
  -- Only rows the seed still owns. Once the owner has corrected one in
  -- the attribute builder, admin_edited is true and the seed never writes
  -- over it again -- see supabase/taxonomy.sql.
  where not attributes.admin_edited;`);

/* options */
const optRows = [];
for (const a of attrs.values()) {
  a.options.forEach((opt, i) =>
    optRows.push(`(${q(a.slug)}, ${q(opt)}, ${i})`));
}
if (optRows.length) {
  L.push("\n-- ---- attribute options (only where the values are universal) ----");
  L.push(`insert into attribute_options (attribute_id, label, value, display_order)
select a.id, v.label, v.label, v.ord
  from (values
  ${vals(optRows)}
  ) as v(attr_slug, label, ord)
  join attributes a on a.slug = v.attr_slug
on conflict (attribute_id, value) do nothing;`);
}

/* assignments */
L.push("\n-- ---- which attributes each product type asks for ----");
L.push(`insert into product_type_attributes (product_type_id, attribute_id, display_order)
select pt.id, a.id, v.ord
  from (values
  ${vals(links.map((l) => {
    const [catSlug, subSlug, typeSlug] = l.typeKey.split("|");
    return `(${q(catSlug + "__" + subSlug)}, ${q(typeSlug)}, ${q(l.attrSlug)}, ${l.order})`;
  }))}
  ) as v(cat_slug, type_slug, attr_slug, ord)
  join categories    c  on c.slug  = v.cat_slug
  join product_types pt on pt.category_id = c.id and pt.slug = v.type_slug
  join attributes    a  on a.slug  = v.attr_slug
on conflict (product_type_id, attribute_id) do nothing;`);

const out = L.join("\n") + "\n";
fs.writeFileSync(path.join(ROOT, "supabase/taxonomy-seed.sql"), out);

console.log(`supabase/taxonomy-seed.sql
  ${cats.size} categories
  ${subs.size} subcategories
  ${types.length} product types
  ${attrs.size} attributes
  ${[...attrs.values()].reduce((n, a) => n + a.options.length, 0)} options
  ${links.length} assignments
  ${out.split("\n").length} lines, ${(out.length / 1024).toFixed(0)} KB`);
